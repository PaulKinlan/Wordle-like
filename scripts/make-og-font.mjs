// Makes worker/og-font.ts: the glyphs the Worker needs to draw link-preview
// images (worker/og.ts), pre-rendered from Inter (SIL Open Font License) as
// alpha bitmaps. Run once, or when the character set changes:
//
//   npm pack @fontsource/inter@5.3.0 && tar xzf fontsource-inter-5.3.0.tgz
//   node scripts/make-og-font.mjs package/files
//
// Uses the pre-installed Chromium (Playwright) to draw the glyphs on a canvas.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { deflateSync } from 'node:zlib';
import { createRequire } from 'node:module';

// Playwright is installed globally (CommonJS), not as a project dependency.
const { chromium } = createRequire(import.meta.url)('playwright');

const dir = process.argv[2];
if (!dir) throw new Error('Usage: node scripts/make-og-font.mjs <dir with inter-*.woff2>');
const font = (name) => readFileSync(join(dir, name)).toString('base64');

const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i));
const TEXT = [...range(0x20, 0x7e), ...range(0xa1, 0xff), ...range(0x100, 0x17f), '·', '–', '’', '…'].filter((c) => c !== '×' && c !== '÷');

const FACES = [
  { name: 'score', weight: 800, size: 230, chars: [...'0123456789/X'] },
  { name: 'title', weight: 800, size: 64, chars: TEXT },
  { name: 'line', weight: 800, size: 48, chars: TEXT },
  { name: 'body', weight: 600, size: 40, chars: TEXT },
];

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<!doctype html><body></body>');
const out = await page.evaluate(
  async ({ faces, fonts }) => {
    for (const [weight, latin, ext] of [
      [600, fonts.l600, fonts.e600],
      [800, fonts.l800, fonts.e800],
    ]) {
      for (const [src, ur] of [
        [latin, 'U+0000-00FF, U+2013, U+2019, U+2026'],
        [ext, 'U+0100-017F'],
      ]) {
        const f = new FontFace('Inter', `url(data:font/woff2;base64,${src})`, { weight: String(weight), unicodeRange: ur });
        document.fonts.add(await f.load());
      }
    }
    const result = {};
    for (const face of faces) {
      const css = `${face.weight} ${face.size}px Inter`;
      const probe = document.createElement('canvas').getContext('2d');
      probe.font = css;
      const m = probe.measureText('Hg');
      const ascent = Math.ceil(m.fontBoundingBoxAscent);
      const descent = Math.ceil(m.fontBoundingBoxDescent);
      const cellH = ascent + descent + 4;
      // Lay glyphs out in rows of a fixed-width atlas.
      const W = 2048;
      const boxes = [];
      let x = 0;
      let y = 0;
      for (const ch of face.chars) {
        const t = probe.measureText(ch);
        const left = Math.floor(-t.actualBoundingBoxLeft) - 1;
        const w = Math.max(1, Math.ceil(t.actualBoundingBoxRight) - left + 2);
        if (x + w > W) {
          x = 0;
          y += cellH;
        }
        boxes.push({ ch, x, y, w, left, adv: t.width });
        x += w;
      }
      const H = y + cellH;
      const canvas = document.createElement('canvas');
      canvas.width = W;
      canvas.height = H;
      const ctx = canvas.getContext('2d');
      ctx.font = css;
      ctx.fillStyle = '#000';
      ctx.textBaseline = 'alphabetic';
      for (const b of boxes) ctx.fillText(b.ch, b.x - b.left, b.y + ascent + 2);
      const rgba = ctx.getImageData(0, 0, W, H).data;
      const alpha = new Array(W * H);
      for (let i = 0; i < W * H; i++) alpha[i] = rgba[i * 4 + 3];
      result[face.name] = {
        size: face.size,
        ascent: ascent + 2,
        height: cellH,
        width: W,
        rows: H,
        alpha,
        glyphs: Object.fromEntries(boxes.map((b) => [b.ch, [b.x, b.y, b.w, b.left, Math.round(b.adv * 100) / 100]])),
      };
    }
    return result;
  },
  {
    faces: FACES,
    fonts: {
      l600: font('inter-latin-600-normal.woff2'),
      e600: font('inter-latin-ext-600-normal.woff2'),
      l800: font('inter-latin-800-normal.woff2'),
      e800: font('inter-latin-ext-800-normal.woff2'),
    },
  },
);
await browser.close();

let ts = `// Generated by scripts/make-og-font.mjs. Do not edit.
// Glyphs from Inter by Rasmus Andersson, SIL Open Font License 1.1.
// Each face: an alpha atlas (zlib, base64) and per glyph [x, y, width, left bearing, advance].
export interface OgFace {
  size: number;
  ascent: number;
  height: number;
  width: number;
  rows: number;
  atlas: string;
  glyphs: Record<string, [number, number, number, number, number]>;
}

`;
for (const [name, f] of Object.entries(out)) {
  const atlas = deflateSync(Buffer.from(f.alpha), { level: 9 }).toString('base64');
  const { alpha: _alpha, ...rest } = f;
  ts += `export const ${name}: OgFace = ${JSON.stringify({ ...rest, atlas })};\n\n`;
  console.log(name, `${f.width}x${f.rows}`, `${Math.round(atlas.length / 1024)} KB`);
}
writeFileSync(new URL('../worker/og-font.ts', import.meta.url), ts);
